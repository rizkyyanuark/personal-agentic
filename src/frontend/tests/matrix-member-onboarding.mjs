import assert from "node:assert/strict";
import { readFile, writeFile, mkdir, mkdtemp } from "node:fs/promises";
import path from "node:path";
import { chromium, expect } from "@playwright/test";

const base = process.env.AE_TEST_URL;
const org = process.env.AE_TEST_ORG;
const out = process.env.AE_TEST_OUTPUT;
assert(base && org && out && new URL(base).hostname === "127.0.0.1", "Only disposable loopback controller is allowed");
const key = (await readFile(path.join(org, ".state/owner.key"), "utf8")).trim();
const browser = await chromium.launch({ channel: "chrome", headless: true });
const owner = await browser.newContext({ baseURL: base, viewport: { width: 1360, height: 960 } });
const recipient = await browser.newContext({ baseURL: base, viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
const checks = [];
const pageErrors = [];
const urls = [];
const tokenValues = [];
for (const context of [owner, recipient]) {
  context.on("page", page => page.on("pageerror", e => pageErrors.push(e.message)));
  context.on("request", request => urls.push(request.url()));
}
const record = label => { checks.push({ check: label, passed: true }); console.log("PASS browser", label); };
try {
  const login = await owner.request.post("/api/login", { data: { token: key } });
  assert.equal(login.status(), 200);
  const page = await owner.newPage();
  await page.goto("/settings/workspace");
  const create = page.getByRole("button", { name: "Create invitation", exact: true });
  await expect(create).toBeEnabled({ timeout: 45000 });
  // Previous API tests exercise the rate-limit minute; use a new workspace for the browser flow.
  const name = "Browser invitation workspace";
  const response = await owner.request.post("/api/tenants", { data: { name } });
  assert.equal(response.status(), 200);
  const tenant = await response.json();
  await owner.addCookies([{ name: "ae_workspace", value: tenant.id, url: base, sameSite: "Strict" }]);
  await page.reload();
  await expect(create).toBeEnabled({ timeout: 45000 });
  await create.click();
  const link = await page.getByLabel("Invitation link — shown only now").inputValue();
  tokenValues.push(new URLSearchParams(new URL(link).hash.slice(1)).get("invite"));
  await expect(page.getByText("Invitation created. Copy and share its link privately.", { exact: true })).toHaveCount(1);
  record("Owner creates a real invitation with one toast and no password field");
  assert.equal(await page.locator(".matrix-invitations input[type=password]").count(), 0);
  // Clipboard availability is an external browser permission boundary, not product behavior.
  await page.evaluate(() => { Object.defineProperty(navigator.clipboard, "writeText", { configurable: true, value: async () => { throw new DOMException("Denied", "NotAllowedError"); } }); });
  await page.getByRole("button", { name: "Copy invitation link", exact: true }).click();
  await expect(page.getByText("Copy was blocked. Select the invitation link and copy it manually.", { exact: true })).toHaveCount(1);
  await expect(page.getByLabel("Invitation link — shown only now")).toHaveValue(link);
  record("Clipboard denial emits one toast and leaves manual-copy control");
  await page.getByRole("button", { name: "Hide link", exact: true }).click();
  await expect(page.locator("#new-member-link")).toHaveCount(0);
  const join = await recipient.newPage();
  await join.goto(link);
  await expect(join.getByRole("form", { name: "Accept invitation" })).toBeVisible();
  assert.equal(new URL(join.url()).hash, "");
  assert.equal(new URL(join.url()).search, "");
  await expect(join.getByText(name, { exact: true })).toBeVisible();
  const store = await join.evaluate(() => JSON.stringify([Object.entries(localStorage), Object.entries(sessionStorage)]));
  assert(!store.includes(tokenValues[0]));
  record("Fragment intake clears the URL and does not persist token in browser storage");
  const before = await (await owner.request.get(`/api/tenants/${tenant.id}/invitations`)).json();
  assert.equal(before.invitations[0].status, "pending");
  record("Opening the invitation creates no Matrix account or membership");
  const username = `browser.${Date.now().toString(36)}`;
  const password = `Browser-pass-${crypto.randomUUID()}`;
  await join.getByLabel("Username", { exact: true }).fill(username);
  await join.getByLabel("Choose password", { exact: true }).fill(password);
  await join.getByLabel("Confirm password", { exact: true }).fill("different");
  await expect(join.getByText("Passwords must match.", { exact: true })).toBeVisible();
  await expect(join.getByRole("button", { name: "Create account and join", exact: true })).toBeDisabled();
  record("Password confirmation remains field validation without a duplicate toast");
  await join.getByLabel("Confirm password", { exact: true }).fill(password);
  await join.getByRole("button", { name: "Create account and join", exact: true }).focus();
  await join.keyboard.press("Enter");
  await expect(join.getByRole("heading", { name: "Your account is ready" })).toBeVisible({ timeout: 45000 });
  await expect(join.getByText("Account created and workspace membership confirmed. You can now sign in.", { exact: true })).toHaveCount(1);
  const accepted = await (await owner.request.get(`/api/tenants/${tenant.id}/members`)).json();
  assert(accepted.some(m => m.user === `@${username}:invite.test` && m.role === "member"));
  record("Keyboard acceptance creates a real account and Member membership before success");
  const geometry = await join.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
  assert(geometry.scroll <= geometry.width);
  await join.screenshot({ path: path.join(out, "join-success-mobile.png"), fullPage: true });
  record("Mobile reduced-motion recipient success fits the viewport");
  assert.equal((await owner.request.get("/api/me").then(r => r.json())).user, "owner");
  record("Recipient acceptance leaves owner browser session unchanged");
  await join.getByRole("link", { name: "Go to sign in" }).click();
  await expect(join.getByRole("form", { name: "Sign in" })).toBeVisible();
  await join.getByLabel("Username", { exact: true }).fill(username);
  await join.getByLabel("Password", { exact: true }).fill(password);
  await join.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(join.locator(".platform-shell")).toBeVisible({ timeout: 45000 });
  const memberTenants = await (await recipient.request.get("/api/tenants")).json();
  assert.deepEqual(memberTenants.map(t => t.id), [tenant.id]);
  record("Recipient signs in through ordinary Matrix form and sees only invited workspace");
  await join.goto("/settings/workspace");
  await expect(join.getByRole("button", { name: "Create invitation", exact: true })).toHaveCount(0);
  record("Member UI does not expose owner invitation controls");
  await create.click();
  const revokedLink = await page.getByLabel("Invitation link — shown only now").inputValue();
  tokenValues.push(new URLSearchParams(new URL(revokedLink).hash.slice(1)).get("invite"));
  const pendingRow = page.getByRole("list", { name: "New-member invitations" }).getByRole("listitem").filter({ hasText: "Unclaimed invitation" }).first();
  await pendingRow.getByRole("button", { name: "Revoke invitation", exact: true }).click();
  await expect(page.getByText("Invitation revoked. Any previously created Matrix account remains.", { exact: true })).toHaveCount(1);
  const expired = await recipient.newPage();
  await expired.goto(revokedLink);
  await expect(expired.getByText(/This invitation is missing, unavailable/)).toBeVisible();
  await expired.getByRole("button", { name: "Check invitation again" }).click();
  await expect(expired.getByText("This invitation is invalid, expired, revoked, or no longer authorized. Ask the owner for a new invitation.", { exact: true })).toHaveCount(1);
  record("Revoked link offers safe recovery and one action-error toast");
  // A signed-in owner may open the join route without silently losing their existing session.
  await create.click();
  const signedLink = await page.getByLabel("Invitation link — shown only now").inputValue();
  tokenValues.push(new URLSearchParams(new URL(signedLink).hash.slice(1)).get("invite"));
  const signedPage = await owner.newPage();
  await signedPage.goto(signedLink);
  await expect(signedPage.getByLabel("Username", { exact: true })).toBeVisible();
  await signedPage.getByLabel("Username", { exact: true }).fill("owner");
  await signedPage.getByLabel("Choose password", { exact: true }).fill(password);
  await signedPage.getByLabel("Confirm password", { exact: true }).fill(password);
  await signedPage.getByRole("button", { name: "Create account and join", exact: true }).click();
  await expect(signedPage.getByText(/Platform and bot names are reserved\.$/)).toHaveCount(1);
  assert.equal((await owner.request.get("/api/me").then(r => r.json())).user, "owner");
  record("Reserved username failure never logs out a signed-in owner");
  await signedPage.setViewportSize({ width: 320, height: 760 });
  await signedPage.screenshot({ path: path.join(out, "join-validation-mobile.png"), fullPage: true });
  assert(await signedPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  record("320px validation/recovery controls remain within viewport");
  // Native browser layout zoom, using the same Chrome profile mechanism as navigation acceptance.
  await owner.close(); await recipient.close(); await browser.close();
  const profile = await mkdtemp(path.join(out, "join-zoom-profile-"));
  const zoomLevel = Math.log(2) / Math.log(1.2);
  const hosts = Object.fromEntries([new URL(base).host, new URL(base).hostname, "localhost"].map(host => [host, { zoom_level: zoomLevel, last_modified: "13300000000000000" }]));
  const partitions = ["x", "", "0", Buffer.from("Default").toString("hex"), "x" + Buffer.from("Default").toString("hex")];
  const preferences = { partition: { default_zoom_level: Object.fromEntries(partitions.map(k => [k, zoomLevel])), per_host_zoom_levels: Object.fromEntries(partitions.map(k => [k, hosts])) } };
  await mkdir(path.join(profile, "Default"), { recursive: true });
  await writeFile(path.join(profile, "Default", "Preferences"), JSON.stringify(preferences));
  await writeFile(path.join(profile, "Preferences"), JSON.stringify(preferences));
  const zoom = await chromium.launchPersistentContext(profile, { channel: "chrome", headless: true, baseURL: base, viewport: { width: 1920, height: 1080 }, args: ["--window-size=1920,1080"] });
  try {
    const zoomPage = zoom.pages()[0] ?? await zoom.newPage();
    await zoomPage.goto(signedLink);
    await expect(zoomPage.getByLabel("Username", { exact: true })).toBeVisible();
    const metrics = await zoomPage.evaluate(() => ({ dpr: devicePixelRatio, width: innerWidth, scroll: document.documentElement.scrollWidth, zoom: getComputedStyle(document.documentElement).zoom, scale: visualViewport.scale }));
    assert(metrics.dpr >= 1.9 && metrics.dpr <= 2.1 && metrics.scroll <= metrics.width && metrics.scale === 1 && ["1", "normal"].includes(metrics.zoom), JSON.stringify(metrics));
    await zoomPage.getByLabel("Username", { exact: true }).focus(); await zoomPage.keyboard.press("Tab");
    await expect(zoomPage.getByLabel("Choose password", { exact: true })).toBeFocused();
    await zoomPage.screenshot({ path: path.join(out, "join-browser-zoom-200.png"), fullPage: true });
    record("Native 200 percent browser zoom preserves layout and keyboard focus order");
  } finally { await zoom.close(); }
  for (const url of urls) {
    assert.equal(new URL(url).origin, base, "No request may disclose invitation credentials to a third party");
    for (const token of tokenValues) assert(!url.includes(token), "Invitation token must never appear in HTTP URL");
  }
  record("All browser requests are same-origin and contain no invitation token in their URLs");
  assert.deepEqual(pageErrors, []);
  await writeFile(path.join(out, "browser-receipt.json"), JSON.stringify({ checks, pageErrors, noAgentTasks: true, browserContexts: 2, externalBoundaryMock: "Clipboard API denied to exercise manual-copy recovery; all account, membership and authentication calls are real" }, null, 2));
  console.log(`${checks.length} real browser onboarding checks passed`);
} finally { await browser.close(); }
