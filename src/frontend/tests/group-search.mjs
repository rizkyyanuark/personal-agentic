import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { expect as playwrightExpect } from "@playwright/test";
const expect = playwrightExpect.configure({ timeout: 30000 });

export async function verifyGroupSearch({ page, request, call, state, until, directory, base, ownerKey }) {
  assert(process.env.AE_TEST_DISPOSABLE === "true" && ["localhost", "127.0.0.1"].includes(new URL(base).hostname), "Use only a disposable loopback controller");
  const beforeRuns = (await state()).runs.length;
  const settleMotion = async locator => locator.evaluate(async element => {
    await Promise.all(element.getAnimations({ subtree: true }).filter(animation => animation.effect?.getComputedTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => null)));
  });
  const canceledDeliveries = [];
  const checks = [];
  const record = text => { checks.push(text); console.log("CHECK", text); };
  const suffix = randomUUID().slice(0, 8);
  const a = await call("/groups", { id: "", name: `Search A ${suffix}`, description: "Disposable real search acceptance" });
  const b = await call("/groups", { id: "", name: `Search B ${suffix}`, description: "Isolation boundary" });
  const marker = `SearchMarker-${suffix}`;
  for (const group of [a, b]) await call("/messages", { id: randomUUID(), group_id: group.id, body: `${marker} in ${group.name}`, recipients: [], reply_to: null, artifacts: [] });
  const location = group => `/groups/${group.id}/chat`;
  const dialog = page.getByRole("dialog", { name: /^Search #/ });
  const query = () => dialog.getByRole("textbox", { name: "Search query" });
  const submit = () => dialog.getByRole("button", { name: "Search", exact: true });
  const open = async group => { await page.goto(location(group)); await page.getByRole("button", { name: `Search #${group.name}`, exact: true }).click(); await expect(query()).toBeFocused(); };
  const close = async () => { await page.keyboard.press("Escape"); await expect(dialog).toHaveCount(0); };
  const search = async value => { await query().fill(value); await submit().click(); await expect(dialog.locator(".search-results")).toHaveAttribute("aria-busy", "false"); };
  const toast = page.locator(".action-toast:not([data-ending-style])");
  let navigation = 0;
  page.on("framenavigated", frame => { if (frame === page.mainFrame()) navigation += 1; });
  let requests = 0;
  page.on("request", r => { if (new URL(r.url()).pathname === "/api/search") requests += 1; });
  await open(a);
  await query().fill(marker);
  await dialog.getByRole("tab", { name: "Documents", exact: true }).click();
  await dialog.getByRole("tab", { name: "Messages", exact: true }).click();
  assert.equal(requests, 0);
  await query().press("Enter");
  await expect(dialog.locator(".search-results article")).toHaveCount(1);
  await expect(dialog.locator(".search-results")).toContainText(a.name);
  await expect(dialog.locator(".search-results")).not.toContainText(b.name);
  assert.equal(requests, 1);
  await expect(toast).toHaveCount(0);
  record("Explicit Enter and active-group message isolation; no passive requests or success toast");
  await search(`nothing-matches-${suffix}`);
  await expect(dialog.locator(".search-results")).toContainText("No messages found in this group.");
  await query().fill("   "); await submit().click();
  await expect(dialog.locator("#search-query-error")).toHaveText("Enter a search query.");
  const invalidBefore = requests;
  await query().fill("🚀".repeat(251)); await submit().click();
  await expect(dialog.locator("#search-query-error")).toContainText("1,000 UTF-8 bytes");
  assert.equal(requests, invalidBefore);
  await search("🚀".repeat(250));
  await expect(dialog.locator(".search-results")).toContainText("No messages found");
  record("Successful empty state, whitespace and exact UTF-8 limit with invalid queries not submitted");

  async function delayed(action, fail = false) {
    let release, resolveStarted, resolveDone, deliveryError;
    const gate = new Promise(resolve => { release = resolve; });
    const started = new Promise(resolve => { resolveStarted = resolve; });
    const done = new Promise(resolve => { resolveDone = resolve; });
    const handler = async route => {
      const navigationAtRequest = navigation;
      const response = await route.fetch();
      assert.equal(response.status(), 200);
      resolveStarted(); await gate;
      try { if (fail) await route.abort("failed"); else await route.fulfill({ response }); }
      catch (error) {
        const failure = route.request().failure()?.errorText;
        if (!/Route is already handled/.test(error.message) || !(navigation !== navigationAtRequest || (failure && /ERR_ABORTED|ERR_FAILED/.test(failure)))) deliveryError = error;
        else canceledDeliveries.push({ cause: "Browser canceled obsolete request", failure: failure ?? null, documentNavigated: navigation !== navigationAtRequest });
      } finally { resolveDone(); }
    };
    await page.route("**/api/search?**", handler, { times: 1 });
    try {
      await query().fill(marker); await submit().click(); await Promise.race([started, new Promise((_, reject) => setTimeout(() => reject(new Error("Delayed search did not reach real response")), 15000))]);
      await expect(dialog.getByRole("button", { name: "Searching…", exact: true })).toBeDisabled();
      const pendingRequests = requests;
      await query().press("Enter"); assert.equal(requests, pendingRequests);
      await action(); release(); await Promise.race([done, new Promise((_, reject) => setTimeout(() => reject(new Error("Delayed response did not settle")), 15000))]);
      if (deliveryError) throw deliveryError;
      await page.unroute("**/api/search?**", handler);
    } finally { release(); await page.unroute("**/api/search?**", handler); }
  }
  await delayed(async () => { await search(`new-draft-${suffix}`); await expect(dialog.locator(".search-results")).toContainText("No messages found"); });
  await expect(dialog.locator(".search-results article")).toHaveCount(0);
  await expect(query()).toHaveValue(`new-draft-${suffix}`);
  await expect(toast).toHaveCount(0);
  await delayed(async () => { await dialog.getByRole("tab", { name: "Documents", exact: true }).click(); });
  await expect(dialog.locator(".search-results article")).toHaveCount(0);
  await dialog.getByRole("tab", { name: "Messages", exact: true }).click();
  await delayed(async () => { await query().fill("new draft after obsolete failure"); }, true);
  await expect(toast).toHaveCount(0);
  await delayed(close);
  const reopenRequests = requests;
  await page.getByRole("button", { name: `Search #${a.name}`, exact: true }).click();
  await expect(dialog.locator(".search-results article")).toHaveCount(0);
  assert.equal(requests, reopenRequests);
  await delayed(async () => { await page.evaluate(url => { history.pushState(null, "", url); window.dispatchEvent(new PopStateEvent("popstate")); }, location(b)); });
  await expect(dialog).toHaveCount(0);
  await page.getByRole("button", { name: `Search #${b.name}`, exact: true }).click();
  await expect(query()).toHaveValue("");
  await search(marker); await expect(dialog.locator(".search-results")).toContainText(b.name);
  await expect(dialog.locator(".search-results")).not.toContainText(a.name);
  await close();
  await page.evaluate(url => { history.pushState(null, "", url); window.dispatchEvent(new PopStateEvent("popstate")); }, location(a));
  await expect(dialog).toHaveCount(0);
  await page.getByRole("button", { name: `Search #${a.name}`, exact: true }).click();
  record("Real delayed-response cancellation on query, mode, close and group changes; duplicate submission blocked");

  const fault = route => route.abort("failed");
  await page.route("**/api/search?**", fault);
  await search(marker);
  await expect(toast.filter({ hasText: "Search could not be completed." })).toHaveCount(1);
  await expect(query()).toHaveValue(marker);
  await expect(dialog).not.toContainText("Search could not be completed.");
  await expect(dialog).not.toContainText("No messages found");
  await toast.getByRole("button", { name: "Dismiss notification", exact: true }).click();
  await page.unroute("**/api/search?**", fault);
  await search(marker); await expect(dialog.locator(".search-results article")).toHaveCount(1);
  record("One failure toast, retained draft, no false empty state and successful explicit real retry");
  await close();
  await page.locator("body").click({ position: { x: 700, y: 180 } });
  await page.keyboard.press("Control+k"); await expect(query()).toBeFocused();
  await query().fill("keyboard draft"); await page.keyboard.press("Control+k"); await expect(query()).toHaveValue("keyboard draft");
  await close();
  await page.goto("/settings/profile"); await page.locator("#account-display-name").focus();
  await page.keyboard.press("Control+k"); await expect(dialog).toHaveCount(0);
  await page.locator("#account-display-name").dispatchEvent("keydown", { key: "k", ctrlKey: true, isComposing: true });
  await expect(dialog).toHaveCount(0);
  await page.goto(location(a));
  await page.getByRole("button", { name: "Manage group", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.keyboard.press("Control+k"); await expect(dialog).toHaveCount(0);
  await page.keyboard.press("Escape");
  record("Working shortcut, repeat focus, editable, composition and other-dialog guards");

  const docResponse = await request.post("/api/artifacts", { multipart: { group_id: a.id, file: { name: "profile-search-notes.md", mimeType: "text/plain", buffer: Buffer.from("Workspace account profile and local group search. Rust controller and native Windows projects.") } } });
  assert(docResponse.ok()); const document = await docResponse.json();
  await call(`/artifacts/${document.id}/index`);
  const indexState = async id => until(async () => { const artifact = (await state()).artifacts.find(x => x.id === id); return artifact && artifact.status !== "indexing" ? artifact : false; }, 600000);
  const indexedDoc = await indexState(document.id); assert.equal(indexedDoc.status, "indexed", indexedDoc.error);
  const canvas = await page.context().newPage(); await canvas.setViewportSize({ width: 256, height: 256 });
  await canvas.setContent('<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240"><rect width="240" height="240" fill="white"/><circle cx="120" cy="120" r="90" fill="red"/></svg>');
  const png = await canvas.screenshot(); await canvas.close();
  const pictureResponse = await request.post("/api/artifacts", { multipart: { group_id: a.id, file: { name: "profile-search-red-circle.png", mimeType: "image/png", buffer: png } } });
  assert(pictureResponse.ok()); const picture = await pictureResponse.json(); await call(`/artifacts/${picture.id}/index`);
  const indexedPicture = await indexState(picture.id); assert.equal(indexedPicture.status, "indexed", indexedPicture.error);
  await open(a);
  await dialog.getByRole("tab", { name: "Documents", exact: true }).click();
  await search("native Windows projects"); await expect(dialog.locator(".search-results a")).toContainText(document.name);
  assert.equal((await request.get(`/api/artifacts/${document.id}`)).status(), 200);
  await dialog.getByRole("tab", { name: "Images", exact: true }).click();
  await search("a red circle on a white background"); await expect(dialog.locator(".search-results a").first()).toContainText(picture.name);
  await settleMotion(dialog);
  await page.screenshot({ path: path.join(directory, "group-search-indexed-image.png"), fullPage: true });
  await close(); await open(b); await dialog.getByRole("tab", { name: "Documents", exact: true }).click(); await search("native Windows projects");
  await expect(dialog.locator(".search-results a")).toHaveCount(0);
  await dialog.getByRole("tab", { name: "Images", exact: true }).click(); await search("red circle"); await expect(dialog.locator(".search-results a")).toHaveCount(0);
  record("Actual CLIP/LanceDB document and image indexing, authorized source file and second-group isolation");
  await close();
  const layouts = [];
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 }); await page.goto(location(a));
    await page.getByRole("button", { name: "Show navigation", exact: true }).click();
    await page.getByRole("button", { name: `Search #${a.name}`, exact: true }).click();
    await expect(dialog).toBeVisible(); await expect(query()).toBeFocused();
    await expect(page.getByRole("dialog", { name: "Workspace navigation", exact: true })).toHaveCount(0);
    const fits = await dialog.evaluate(element => { const r = element.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth + 1 && document.documentElement.scrollWidth <= innerWidth + 1; });
    assert(fits, `Search fits ${width}px`); layouts.push(width);
    await settleMotion(dialog);
    await page.screenshot({ path: path.join(directory, `group-search-${width}.png`), fullPage: true }); await close();
    await expect(page.getByRole("button", { name: "Show navigation", exact: true })).toBeFocused();
  }
  await page.setViewportSize({ width: 1440, height: 980 }); await page.goto(location(a));
  await page.getByRole("button", { name: "Collapse navigation", exact: true }).click();
  await page.locator(".sidebar.rail").getByRole("button", { name: `Search #${a.name}`, exact: true }).click();
  await expect(query()).toBeFocused(); await close();
  await page.getByRole("button", { name: "Expand navigation", exact: true }).click();
  await page.emulateMedia({ reducedMotion: "reduce" }); await open(a);
  assert.equal(await dialog.evaluate(e => getComputedStyle(e).animationName), "none"); await close();
  const cdp = await page.context().newCDPSession(page); await cdp.send("Emulation.setDeviceMetricsOverride", { width: 720, height: 490, deviceScaleFactor: 1, mobile: false, scale: 0.5 });
  await page.goto("/settings/profile"); await expect(page.locator("#account-display-name")).toBeVisible();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(directory, "profile-200-percent.png"), fullPage: true }); await cdp.send("Emulation.clearDeviceMetricsOverride"); await cdp.detach();
  record("320/390 mobile single-overlay and return focus, rail shortcut, reduced motion and 200 percent equivalent viewport");
  assert.equal((await state()).runs.length, beforeRuns, "No agent tasks may be created");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await open(a);
  const tenant = await call("/tenants", { name: `Search scope ${suffix}` });
  await delayed(async () => {
    await page.context().addCookies([{ name: "ae_workspace", value: tenant.id, url: base }]);
    await page.reload();
  });
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Search unavailable: select a group to search", exact: true })).toBeDisabled();
  await page.goto("/groups/general/chat");
  await page.getByRole("button", { name: "Search #General", exact: true }).click();
  await expect(query()).toHaveValue(""); await expect(dialog.locator(".search-results article")).toHaveCount(0); await close();
  await page.context().addCookies([{ name: "ae_workspace", value: "default", url: base }]); await page.reload();
  await open(a);
  const { human } = JSON.parse(await readFile(process.env.AE_TEST_MATRIX_CREDENTIALS_FILE, "utf8"));
  await call("/tenants/default/members", { user: human.user_id, role: "member" });
  await delayed(async () => {
    const response = await request.post("/api/login", { data: { username: human.username, password: human.password } }); assert.equal(response.status(), 200);
    await page.goto("/settings/profile");
  });
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("button", { name: /^Search #/ })).toHaveCount(0);
  await expect(page.locator(".profile-details")).toContainText(human.user_id);
  assert.equal((await request.post("/api/login", { data: { token: ownerKey } })).status(), 200);
  await open(a);
  await delayed(async () => { assert.equal((await request.post("/api/logout")).status(), 200); await page.goto("/"); });
  await expect(page.getByRole("heading", { name: "Welcome back", exact: true })).toBeVisible(); await expect(dialog).toHaveCount(0);
  assert.equal((await request.post("/api/login", { data: { token: ownerKey } })).status(), 200); await page.goto(location(a));
  await call(`/tenants/${tenant.id}`, {}, "DELETE");
  record("Delayed real responses after workspace-cookie change, identity replacement and logout cannot reappear; Member search remains unavailable");
  const macContext = await page.context().browser().newContext({ baseURL: base });
  await macContext.addInitScript(() => Object.defineProperty(navigator, "platform", { get: () => "MacIntel" }));
  assert.equal((await macContext.request.post("/api/login", { data: { token: ownerKey } })).status(), 200);
  const macPage = await macContext.newPage(); await macPage.goto(location(a));
  await expect(macPage.getByRole("button", { name: `Search #${a.name}`, exact: true })).toBeVisible();
  await macPage.getByRole("heading", { name: a.name, exact: true }).click();
  await macPage.keyboard.press("Meta+k");
  await expect(macPage.getByRole("textbox", { name: "Search query" })).toBeFocused();
  await macPage.keyboard.press("Escape");
  await expect(macPage.locator(".search-button kbd")).toHaveText("⌘ K");
  await macContext.close();
  record("Command+K and matching Mac hint verified with browser platform override; native macOS hardware is not claimed");
  const anonymous = await page.context().browser().newContext({ baseURL: base });
  assert.equal((await anonymous.request.get(`/api/search?group_id=${a.id}&q=${marker}`)).status(), 401); await anonymous.close();
  record("Anonymous search denied and zero agent runs");
  const result = { checkedAt: new Date().toISOString(), checks, layouts, requests, groups: [a.id, b.id], indexedArtifacts: [document.id, picture.id], runsBefore: beforeRuns, runsAfter: (await state()).runs.length,
    mocks: false, canceledDeliveries, hardwareSimulation: "navigator.platform is overridden only in a separate browser context for the macOS shortcut branch; no API or search results are mocked.", faultInjection: "One local network request is intentionally aborted; real successful responses are delayed for race tests without changing their content.", base };
  await writeFile(path.join(directory, "group-search-receipt.json"), JSON.stringify(result, null, 2));
  return result;
}
